#!/usr/bin/env node
/** Explicitly synthetic provider-contract example, NOT a JEV benchmark. */
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {RULES_VERSION,createDuel,advanceRound} from '../public/core/rules.js';
import {RNG_VERSION,sha256,initialCells,seedCommitment,deriveSpawn} from '../public/core/crypto.js';
import {PROFILES,POLICY_VERSION,baselineAction,generateCandidates} from '../public/core/evaluate.js';
import {createEvents,verifyBundle} from '../public/core/audit.js';
import {chooseJevAction,DEFAULT_MODEL} from '../server/jev.js';
import {fakeResponse} from '../tests/provider-fixture.js';
import {BUILD_INFO} from '../server/build-info.js';
const folder=resolve(process.argv[2]||'examples/mock-provider');await mkdir(folder,{recursive:true});
const seed=await sha256('explicit-synthetic-provider-contract-example'),matchId=seed.slice(0,32),events=[];
const manifest={schemaVersion:1,matchId,game:'2048',rulesVersion:RULES_VERSION,rngVersion:RNG_VERSION,
  policyVersion:POLICY_VERSION,difficulty:'normal',profile:PROFILES.normal,model:DEFAULT_MODEL,
  moveLimit:4,mode:'jev',ranked:false,createdAt:new Date().toISOString(),
  evidenceClass:'mocked-provider-contract-fixture',build:BUILD_INFO,
  note:'Every provider response in this example is synthetic. It is not evidence of live JEV quality, latency, confidence, or cost.'};
const initial=await initialCells(seed),commitment=await seedCommitment(manifest,seed);
let state=createDuel(initial,{matchId,moveLimit:4}),parentSeq=null;
async function emit(type,data){const added=await createEvents(events.at(-1),[{type,data,parentSeq}],{matchId,clockId:'synthetic-example'});events.push(...added);}
await emit('match_started',{manifest,initialCells:initial,commitment});
while(state.status==='active'){
  const humanAction=baselineAction(state.human,'greedy');
  await emit('round_reserved',{requestId:'synthetic-'+state.round,humanAction,expectedRevision:state.revision});parentSeq=events.at(-1).seq;
  const decision=await chooseJevAction({board:state.jev,difficulty:'normal',model:DEFAULT_MODEL,apiKey:'not-a-real-key',
    remainingMoves:4-state.jev.moves,emit,fetcher:async(_url,options)=>Response.json(fakeResponse(JSON.parse(options.body)))});
  await emit('decision_selected',{action:decision.action,source:decision.source,stateHash:await sha256(state.jev)});
  const spawnEvent=await deriveSpawn(seed,state.round),applied=advanceRound(state,{humanAction,jevAction:decision.action,spawnEvent});
  await emit('round_committed',{actions:{human:humanAction,jev:decision.action},state:applied.state,details:applied.details,spawnEvent,decision,
    humanCandidates:generateCandidates(state.human,'easy'),preStateHash:await sha256(state),postStateHash:await sha256(applied.state)});state=applied.state;
}
const bundle={formatVersion:1,manifest,commitment,seed,finalState:state,status:state.status,head:events.at(-1).hash,events,telemetry:[]};
await verifyBundle(bundle,{requireComplete:true});await writeFile(resolve(folder,'audit.json'),JSON.stringify(bundle,null,2));
await writeFile(resolve(folder,'README.md'),'# Synthetic provider contract example\n\nAll responses are generated by tests/provider-fixture.js. No live TypeSafe API was contacted. Scores, confidence, token counts, and latency here are test fixtures, not measured JEV performance.\n');
console.log(folder);
